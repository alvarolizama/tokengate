  @spec today_live_bundle() :: %{today: map(), day_by_hour: [map()]}
  def today_live_bundle do
    from = Tokengate.Periods.start_of_day_utc("Etc/UTC")

    rows =
      RequestLog
      |> where([rl], rl.inserted_at >= ^from)
      |> group_by([rl], [
        fragment("CAST(EXTRACT(hour FROM ?) AS integer)", rl.inserted_at),
        rl.provider_id
      ])
      |> select([rl], %{
        hour: fragment("CAST(EXTRACT(hour FROM ?) AS integer)", rl.inserted_at),
        provider_id: rl.provider_id,
        request_count: count(rl.id),
        cost_usd: fragment("COALESCE(SUM(?), 0)", rl.provider_cost_usd),
        prompt_tokens: fragment("COALESCE(SUM(?), 0)", rl.prompt_tokens),
        completion_tokens: fragment("COALESCE(SUM(?), 0)", rl.completion_tokens),
        cache_read_tokens: fragment("COALESCE(SUM(?), 0)", rl.cache_read_tokens),
        cache_creation_tokens: fragment("COALESCE(SUM(?), 0)", rl.cache_creation_tokens),
        # AVG skips NULLs: carry sum + non-null sample count so the flat
        # weighted average below keeps exactly AVG's semantics.
        latency_sum_ms: fragment("COALESCE(SUM(?), 0)", rl.latency_ms),
        latency_samples: fragment("COUNT(?)", rl.latency_ms),
        error_count: fragment("COUNT(*) FILTER (WHERE status_code >= 400)")
      })
      |> Repo.all()

    %{today: day_totals(rows), day_by_hour: build_day_by_hour(rows)}
  end

  # Flat day totals out of the grouped (hour, provider) rows: exact sums of
  # sums — the same numbers the three separate scans used to produce.
  defp day_totals(rows) do
    %{
      requests_total: Enum.reduce(rows, 0, &(&1.request_count + &2)),
      cost_usd:
        Enum.reduce(rows, Decimal.new(0), fn row, acc -> Decimal.add(acc, row.cost_usd) end),
      prompt_tokens: Enum.reduce(rows, 0, &(&1.prompt_tokens + &2)),
      completion_tokens: Enum.reduce(rows, 0, &(&1.completion_tokens + &2)),
      cache_read_tokens: Enum.reduce(rows, 0, &(&1.cache_read_tokens + &2)),
      cache_creation_tokens: Enum.reduce(rows, 0, &(&1.cache_creation_tokens + &2)),
      avg_latency_ms: weighted_avg_latency(rows),
      error_count: Enum.reduce(rows, 0, &(&1.error_count + &2))
    }
  end

  defp weighted_avg_latency(rows) do
    samples = Enum.reduce(rows, 0, &(&1.latency_samples + &2))

    if samples > 0 do
      total_ms = Enum.reduce(rows, 0, &(&1.latency_sum_ms + &2))
      Float.round(total_ms / samples, 1)
    else
      nil
    end
  end

  # Hour × provider profile (zero-filled 0..23) from the same grouped rows
  # the flat totals were reduced from.
  defp build_day_by_hour(rows) do
    identities = provider_identity_by_id(rows)

    rows
    |> Enum.map(fn row ->
      identity = Map.get(identities, row.provider_id, %{name: @no_provider, logo_url: nil})

      %{
        hour: row.hour,
        provider_name: identity.name || @no_provider,
        provider_logo_url: identity.logo_url,
        requests: row.request_count,
        cost_usd: Decimal.new(to_string(row.cost_usd))
      }
    end)
    |> Enum.group_by(& &1.hour)
    |> then(fn by_hour ->
      for hour <- 0..23 do
        # Varios `provider_id` pueden compartir nombre (o no tener nombre):
        # se colapsan en una sola fila del desglose, como en el resto de
        # las gráficas apiladas del hub.
        providers =
          by_hour
          |> Map.get(hour, [])
          |> Enum.group_by(& &1.provider_name)
          |> Enum.map(fn {name, entries} ->
            %{
              provider_name: name,
              # El logo también se colapsa: sirve el del primer id que traiga
              # uno del catálogo.
              provider_logo_url: Enum.find_value(entries, & &1.provider_logo_url),
              requests: Enum.reduce(entries, 0, &(&1.requests + &2)),
              cost_usd:
                Enum.reduce(entries, Decimal.new(0), fn e, acc ->
                  Decimal.add(acc, e.cost_usd)
                end)
            }
          end)
          |> Enum.sort_by(& &1.requests, :desc)

        %{
          hour: hour,
          total_requests: Enum.reduce(providers, 0, &(&1.requests + &2)),
          total_cost_usd:
            Enum.reduce(providers, Decimal.new(0), fn p, acc ->
              Decimal.add(acc, p.cost_usd)
            end),
          providers: providers
        }
      end
    end)
  end

  # Identidad de cada proveedor presente en las filas agregadas (nombre y logo
  # del catálogo), en una sola consulta: el logo de models.dev viaja con la
  # misma tarjeta que el nombre, sin un lookup por proveedor.
  defp provider_identity_by_id(rows) do
    ids = rows |> Enum.map(& &1.provider_id) |> Enum.reject(&is_nil/1) |> Enum.uniq()

    case ids do
      [] ->
        %{}

      ids ->
        Tokengate.Providers.Provider
        |> where([p], p.id in ^ids)
        |> select([p], {p.id, p.name, p.logo_url})
        |> Repo.all()
        |> Map.new(fn {id, name, logo_url} -> {id, %{name: name, logo_url: logo_url}} end)
    end
  end

  @doc """
  Top cost drivers in the last `minutes` minutes (default 15, limit 5 per axis)
  for the "En vivo" tab. Bounded by `inserted_at >= now - minutes*60` so it
  only ever touches today's partition.

  Returns:

      %{
        window_minutes: 15,
        top_models: [%{model_id, model_name, request_count, error_count, cost_usd}],
        top_consumers: [%{subject_type, subject_id, label, sublabel, request_count, error_count, cost_usd}],
        top_agents: [%{key, label, logo, icon, request_count, error_count, cost_usd}]
      }
  """
  @spec live_cost_drivers(pos_integer(), pos_integer()) :: map()
  def live_cost_drivers(minutes \\ 15, limit \\ 5) do
    cutoff =
      DateTime.utc_now()
      |> DateTime.add(-minutes * 60, :second)
      |> DateTime.truncate(:second)

    base = where(RequestLog, [rl], rl.inserted_at >= ^cutoff)

    model_rows =
      base
      |> group_by([rl], [rl.model_id, rl.model_requested])
      |> order_by([rl],
        desc: fragment("COALESCE(SUM(?), 0)", rl.provider_cost_usd),
        desc: count(rl.id)
      )
      |> limit(^limit)
      |> select([rl], %{
        model_id: rl.model_id,
        model_requested: rl.model_requested,
        request_count: count(rl.id),
        error_count: fragment("COUNT(*) FILTER (WHERE ? >= 400)", rl.status_code),
        cost_usd: fragment("COALESCE(SUM(?), 0)", rl.provider_cost_usd),
        prompt_tokens: fragment("COALESCE(SUM(?), 0)", rl.prompt_tokens),
        cache_read_tokens: fragment("COALESCE(SUM(?), 0)", rl.cache_read_tokens)
      })
      |> Repo.all()

    model_ids = model_rows |> Enum.map(& &1.model_id) |> Enum.reject(&is_nil/1) |> Enum.uniq()

    model_names =
      if model_ids == [] do
        %{}
      else
        Tokengate.Providers.Model
        |> where([m], m.id in ^model_ids)
        |> select([m], {m.id, m.name})
        |> Repo.all()
        |> Map.new()
      end

    top_models =
      Enum.map(model_rows, fn r ->
        %{
          model_id: r.model_id,
          model_name: Map.get(model_names, r.model_id) || r.model_requested || "—",
          request_count: r.request_count,
          error_count: r.error_count || 0,
          cost_usd: Decimal.new(to_string(r.cost_usd)),
          prompt_tokens: r.prompt_tokens || 0,
          cache_read_tokens: r.cache_read_tokens || 0
        }
      end)

    consumer_rows =
      base
      |> group_by([rl], [rl.subject_type, rl.user_id, rl.service_id])
      |> order_by([rl],
        desc: fragment("COALESCE(SUM(?), 0)", rl.provider_cost_usd),
        desc: count(rl.id)
      )
      |> limit(^limit)
      |> select([rl], %{
        subject_type: rl.subject_type,
        user_id: rl.user_id,
        service_id: rl.service_id,
        request_count: count(rl.id),
        error_count: fragment("COUNT(*) FILTER (WHERE ? >= 400)", rl.status_code),
        cost_usd: fragment("COALESCE(SUM(?), 0)", rl.provider_cost_usd)
      })
      |> Repo.all()

    top_consumers = resolve_live_consumers(consumer_rows)

    agent_rows =
      base
      |> group_by([rl], [rl.agent_type, rl.client_agent])
      |> select([rl], %{
        agent_type: rl.agent_type,
        client_agent: rl.client_agent,
        request_count: count(rl.id),
        error_count: fragment("COUNT(*) FILTER (WHERE ? >= 400)", rl.status_code),
        cost_usd: fragment("COALESCE(SUM(?), 0)", rl.provider_cost_usd)
      })
      |> Repo.all()

    top_agents =
      agent_rows
      |> Enum.group_by(fn r -> Tokengate.Agents.identify(r.client_agent, r.agent_type).key end)
      |> Enum.map(fn {_key, [first | _] = buckets} ->
        id = Tokengate.Agents.identify(first.client_agent, first.agent_type)

        %{
          key: id.key,
          label: id.label,
          logo: id.logo,
          icon: id.icon,
          request_count: Enum.reduce(buckets, 0, &(&1.request_count + &2)),
          error_count: Enum.reduce(buckets, 0, &((&1.error_count || 0) + &2)),
          cost_usd:
            Enum.reduce(buckets, Decimal.new(0), fn b, acc ->
              Decimal.add(acc, Decimal.new(to_string(b.cost_usd || 0)))
            end)
        }
      end)
      |> Enum.sort(fn a, b ->
        case Decimal.compare(a.cost_usd, b.cost_usd) do
          :eq -> a.request_count >= b.request_count
          :gt -> true
          :lt -> false
        end
      end)
      |> Enum.take(limit)

    %{
      window_minutes: minutes,
      top_models: top_models,
      top_consumers: top_consumers,
      top_agents: top_agents
    }
  end

  defp resolve_live_consumers([]), do: []

  defp resolve_live_consumers(rows) do
    user_ids = rows |> Enum.map(& &1.user_id) |> Enum.reject(&is_nil/1) |> Enum.uniq()
    service_ids = rows |> Enum.map(& &1.service_id) |> Enum.reject(&is_nil/1) |> Enum.uniq()

    users =
      if user_ids == [] do
        %{}
      else
        Tokengate.Accounts.User
        |> where([u], u.id in ^user_ids)
        |> select([u], {u.id, u.email, u.name})
        |> Repo.all()
        |> Map.new(fn {id, email, name} -> {id, %{email: email, name: name}} end)
      end

    services =
      if service_ids == [] do
        %{}
      else
        Tokengate.Accounts.Service
        |> where([s], s.id in ^service_ids)
        |> select([s], {s.id, s.name})
        |> Repo.all()
        |> Map.new()
      end

    Enum.map(rows, fn r ->
      cond do
        r.subject_type == "service" and r.service_id ->
          %{
            subject_type: "service",
            subject_id: r.service_id,
            label: Map.get(services, r.service_id, "—"),
            sublabel: nil,
            request_count: r.request_count,
            error_count: r.error_count || 0,
            cost_usd: Decimal.new(to_string(r.cost_usd))
          }

        r.user_id ->
          u = Map.get(users, r.user_id)

          %{
            subject_type: "user",
            subject_id: r.user_id,
            label: (u && (u.name || u.email)) || "—",
            sublabel: u && u.email,
            request_count: r.request_count,
            error_count: r.error_count || 0,
            cost_usd: Decimal.new(to_string(r.cost_usd))
          }

        true ->
          %{
            subject_type: "unknown",
            subject_id: nil,
            label: "—",
            sublabel: nil,
            request_count: r.request_count,
            error_count: r.error_count || 0,
            cost_usd: Decimal.new(to_string(r.cost_usd))
          }
      end
    end)
  end

  @doc """
