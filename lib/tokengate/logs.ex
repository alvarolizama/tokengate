  @spec service_stats(binary(), keyword() | map()) :: map()
  def service_stats(service_id, opts \\ []) do
    opts_map =
      cond do
        is_map(opts) -> opts
        is_list(opts) -> Map.new(opts)
        true -> %{}
      end
