defmodule Tokengate.Logs do
  @moduledoc """
  The Logs context: append-only request log entries.

  In normal operation this context only **inserts** and **queries** request
  logs — never updates or deletes. The single deliberate exception is the
  admin utility `truncate_request_logs/0` (destructive maintenance TRUNCATE).
  The `request_logs` table is a native Postgres RANGE-partitioned
  table on `inserted_at` (daily granularity).

  ## Privacy

  This table **never** stores prompt or completion content — only metadata
  (token counts, costs, latency, status). No PII or request/response bodies
  are persisted here.
  """

  import Ecto.Query, warn: false
  alias Tokengate.Repo
  alias Tokengate.Logs.RequestLog
  alias Tokengate.Accounts.GroupMember
  alias Tokengate.Metrics.ConsumptionCounters
  alias Tokengate.Metrics.RequestMetricsHourly

  @default_limit 50
  @max_limit 500

  # Default look-back of the real-time feed (`list_feed/1`). With ~90 live
  # partitions, an unbounded "newest first" read walks every partition until
  # it collects a page — on each filter change. Two days keeps "yesterday"
  # inside the feed at any hour while bounding the walk to a couple of
  # partitions.
  @feed_window_hours 48

  # Hours the RollupWorker re-aggregates on every tick: buckets newer than this
  # may be missing rows in `request_metrics_hourly`, so the hybrid lifetime
  # aggregates read them from raw request_logs instead.
  @rollup_tail_hours 3

  # Stats reads scan raw request_logs across whole windows; cold, they can
  # exceed the DBConnection default (15s) in production — that was the
  # failure behind the stats pages erroring on long periods. Analytics
  # reads get their own, generous budget instead of raising the Repo-wide
  # timeout (which would also cover the proxy auth/write path). Same
  # convention as `Metrics.Rollup` and `Metrics.StatsQueries`.
  @stats_timeout 120_000

  require Logger

  defp stats_timeout,
    do: Application.get_env(:tokengate, :stats_query_timeout_ms, @stats_timeout)

  # Etiqueta de los logs sin proveedor en el desglose por hora del día
  # (fallo antes del routing, o provider ya borrado). Es un valor de DATOS:
  # `Metrics.Rollup` tiene que devolver el MISMO string para que la tarjeta
  # compartida no cambie de nombre entre pestañas. La traducción se hace al
  # pintar (`TokengateWeb.StatsHelpers.provider_label/1`).
  @no_provider "no provider"

  # ---------------------------------------------------------------------------
  # Insert
  # ---------------------------------------------------------------------------

  @doc """
  Inserts a request log entry. Generates `id` and `inserted_at` (defaults to
  `DateTime.utc_now() |> DateTime.truncate(:second)`) if not provided in attrs.

  The insert carries an `ON CONFLICT (oban_job_id, inserted_at) DO NOTHING`
  backstop: when the caller passes an `oban_job_id` (Oban retry of a
  `WriteWorker` job), a row for the same pair can never be duplicated at the
  DB level. It is NOT the dedupe signal — `WriteWorker` pre-checks with
  `request_log_seen?/1` — because with a client-autogenerated UUID Ecto
  returns `{:ok, struct}` even when nothing was inserted. NULL `oban_job_id`
  rows never conflict (Postgres treats NULLs as distinct).

  Returns `{:ok, request_log}` or `{:error, changeset}`.
  """
  def log_request(attrs) do
    inserted_at =
      Map.get(attrs, :inserted_at) ||
        Map.get(attrs, "inserted_at") ||
        DateTime.utc_now() |> DateTime.truncate(:second)

    attrs =
      attrs
      |> ensure_atom_key(:inserted_at, inserted_at)

    %RequestLog{}
    |> RequestLog.changeset(attrs)
    |> Repo.insert(on_conflict: :nothing, conflict_target: [:oban_job_id, :inserted_at])
  end

  @doc """
  True when a request log row already exists for the given Oban job id.

  The `WriteWorker` idempotency pre-check: Oban never executes the same job
  concurrently (attempts are sequential), so seeing a row for the job id
  means an earlier attempt already inserted it — and already delivered the
  webhook dispatch and the `{:new_log, _}` broadcast. `nil` (jobs performed
  outside Oban) is never "seen".
  """
  def request_log_seen?(oban_job_id)

  def request_log_seen?(nil), do: false

  def request_log_seen?(oban_job_id) do
    Repo.exists?(from rl in RequestLog, where: rl.oban_job_id == ^oban_job_id)
  end

  # Partition-pruned variant: request_logs is partitioned by day, so probing
  # by oban_job_id alone indexes every partition (measured ~91 index-only
  # scans / 0.78ms). The unique key is (oban_job_id, inserted_at), and the
  # worker always knows the timestamp from the job args — pinning it prunes
  # to a single partition.
  def request_log_seen?(nil, _), do: false

  # Jobs legacy encolados ANTES de que el proxy fijara `inserted_at` en los
  # args: el timestamp no viaja en el payload, `parse_inserted_at/1` devuelve
  # nil y esta cláusula evita un `FunctionClauseError` que tumbaría el
  # `WriteWorker` en cada reintento (y, con él, el log entero). No se puede
  # probar la partición sin la fecha, así que se responde "no visto": el
  # INSERT sigue siendo idempotente por el índice único.
  def request_log_seen?(_oban_job_id, nil), do: false

  def request_log_seen?(oban_job_id, %DateTime{} = inserted_at) do
    Repo.exists?(
      from rl in RequestLog,
        where:
          rl.oban_job_id == ^oban_job_id and
            rl.inserted_at == ^DateTime.truncate(inserted_at, :second)
    )
  end

  defp ensure_atom_key(map, key, value) when is_map(map) do
    # Accept both atom and string-keyed maps; normalize to atom key.
    map
    |> Map.delete(to_string(key))
    |> Map.put(key, value)
  end

  # ---------------------------------------------------------------------------
  # Query
  # ---------------------------------------------------------------------------

  @doc """
  Fetches one request log by id, with the same preloads as `list_logs/1`
  (member + user + group, service + api_key, provider) so the error-detail
  modal in MonitoringLive can render the row's full context. Returns `nil`
  when no row matches.

  `inserted_at` is optional and comes from the row the caller already has:
  it is the PARTITION KEY, so passing it pins the lookup to that day's
  partition instead of probing every partition kept by retention. Callers
  without the timestamp keep working (a wider, slower read).
  """
  def get_log(id, inserted_at \\ nil) do
    with {:ok, uuid} <- Ecto.UUID.cast(id) do
      RequestLog
      |> where([rl], rl.id == ^uuid)
      |> where_partition(inserted_at)
      |> preload(group_member: [:user, :group])
      |> preload(service: [:api_key])
      |> preload(:provider)
      |> Repo.one()
    else
      _ -> nil
    end
  end

  defp where_partition(query, nil), do: query

  defp where_partition(query, inserted_at) when is_binary(inserted_at) do
    case DateTime.from_iso8601(inserted_at) do
      {:ok, dt, _offset} -> where_partition(query, dt)
      _ -> query
    end
  end

  defp where_partition(query, %DateTime{} = inserted_at) do
    where(query, [rl], rl.inserted_at == ^DateTime.truncate(inserted_at, :second))
  end

  defp where_partition(query, %NaiveDateTime{} = inserted_at) do
    where_partition(query, DateTime.from_naive!(inserted_at, "Etc/UTC"))
  end

  defp where_partition(query, _), do: query

  @doc """
  Lists request logs with optional filters.

  ## Filters (all optional)
    * `:group_member_id` — exact match
    * `:group_member_ids` — list of allowed group_member ids (OR)
    * `:group_id` — exact match, joined through `group_members`
    * `:provider_id` — exact match
    * `:model_id` — exact match
    * `:agent_type` — exact match
    * `:status_code` — exact match
    * `:streaming` — boolean
    * `:from` — `inserted_at >= from` (`DateTime`)
    * `:to` — `inserted_at <= to` (`DateTime`)
    * `:limit` — default 50, max 500

  Date bounds are TOLERANT: an ISO-8601 string (`"2026-11-01"` or
  `"2026-11-01T00:00:00Z"`) is cast, a `Date` covers its whole day, and a
  value that cannot be understood is DROPPED instead of raising
  `Ecto.Query.CastError` — a date filter typed by an operator must never kill
  the LiveView holding it.
  """
  def list_logs(filters \\ %{}) do
    limit = clamp_limit(Map.get(filters, :limit) || Map.get(filters, "limit"))

    RequestLog
    |> apply_log_filters(filters)
    # Keyset order: the id tiebreak makes `before` a total order within a
    # second (`inserted_at` is timestamp(0), so timestamps alone repeat).
    |> order_by([rl], desc: rl.inserted_at, desc: rl.id)
    |> limit(^limit)
    # Only the associations the log rows render: member (email) + its group
    # (badge), the service name and the provider. The nested api_key preload
    # was dead weight — the key column reads `api_key_prefix`/`api_key_id`.
    |> preload(group_member: [:user, :group])
    |> preload(:service)
    |> preload(:provider)
    |> Repo.all()
  end

  @doc """
  The log listing the per-subject stats pages render: same filters, order and
  keyset cursor as `list_logs/1`, but a partial struct with ONLY the columns
  those tables paint (date, model, agent, streaming, status, tokens, cost,
  latency) and no preloads.

  `list_logs/1` stays as it is for the `/logs` feed and Monitoring, which do
  render the associated member/group/service/provider: sharing the full loader
  made every stats page pay 5 preload queries and a `SELECT *` for nothing.
  """
  def list_logs_compact(filters \\ %{}) do
    limit = clamp_limit(Map.get(filters, :limit) || Map.get(filters, "limit"))

    RequestLog
    |> apply_log_filters(filters)
    |> order_by([rl], desc: rl.inserted_at, desc: rl.id)
    |> limit(^limit)
    |> select([rl], %RequestLog{
      id: rl.id,
      inserted_at: rl.inserted_at,
      model_requested: rl.model_requested,
      model_responded: rl.model_responded,
      client_agent: rl.client_agent,
      streaming: rl.streaming,
      status_code: rl.status_code,
      prompt_tokens: rl.prompt_tokens,
      completion_tokens: rl.completion_tokens,
      provider_cost_usd: rl.provider_cost_usd,
      latency_ms: rl.latency_ms
    })
    |> Repo.all()
  end

  @doc """
  The real-time log feed: `list_logs/1` with a DEFAULT look-back window.

  `request_logs` is partitioned by day and retention keeps ~90 of them, so an
  unbounded "newest first" page has to walk partition after partition until
  it fills 50 rows — once per filter change, per viewer. This entry point
  bounds the walk to #{@feed_window_hours}h (1-2 partitions) unless the caller
  passes its own `:from`.

  An explicit `:from` always wins (the operator picked a date range), and the
  keyset `:before` cursor pages INSIDE that window, so "load more" stays
  bounded instead of drifting into the whole history.
  """
  def list_feed(filters \\ %{}) do
    filters
    |> put_feed_window()
    |> list_logs()
  end

  defp put_feed_window(filters) do
    explicit_from = Map.get(filters, :from) || Map.get(filters, "from")

    cond do
      not is_nil(explicit_from) -> filters
      # An explicit cursor-only read is the `list_logs_after/2` shape; it
      # already carries its own bound (`after`), so leave it alone.
      not is_nil(Map.get(filters, :after) || Map.get(filters, "after")) -> filters
      true -> Map.put(filters, :from, feed_window_start())
    end
  end

  defp feed_window_start do
    DateTime.utc_now()
    |> DateTime.add(-@feed_window_hours * 3600, :second)
    |> DateTime.truncate(:second)
  end

  @doc """
  Query feeding the CSV exports, meant for `Repo.stream/2` inside a
  `Repo.transaction/2`.

  Returns a **flat row per log** (a plain map, no struct, NO preloads): the
  associations the CSV needs — member email, group name, provider name — are
  left joins resolved by the database in the same statement, so an export
  issues ONE cursor query instead of the seven round-trips the preload-based
  version spent per 50k rows.

  The caller streams it in chunks and maps each row to CSV cells; nothing
  holds the whole window in memory, and there is no row cap that would
  silently drop the tail of the export.

  Same filters as `list_logs/1`.
  """
  def stream_logs_for_export(filters \\ %{}) do
    RequestLog
    |> apply_log_filters(filters)
    |> join(:left, [rl], gm in assoc(rl, :group_member))
    |> join(:left, [rl, gm], u in assoc(gm, :user))
    |> join(:left, [rl, gm], g in assoc(gm, :group))
    |> join(:left, [rl], p in assoc(rl, :provider))
    |> order_by([rl], desc: rl.inserted_at, desc: rl.id)
    |> select([rl, gm, u, g, p], %{
      inserted_at: rl.inserted_at,
      status_code: rl.status_code,
      model_requested: rl.model_requested,
      model_responded: rl.model_responded,
      user_email: u.email,
      group_name: g.name,
      client_agent: rl.client_agent,
      api_key_id: rl.api_key_id,
      api_key_prefix: rl.api_key_prefix,
      provider_name: p.name,
      provider_key_prefix: rl.provider_key_prefix,
      provider_status_code: rl.provider_status_code,
      error_reason: rl.error_reason,
      error_message: rl.error_message,
      streaming: rl.streaming,
      think: rl.think,
      effort: rl.effort,
      effort_applied: rl.effort_applied,
      prompt_tokens: rl.prompt_tokens,
      completion_tokens: rl.completion_tokens,
      cache_read_tokens: rl.cache_read_tokens,
      cache_creation_tokens: rl.cache_creation_tokens,
      latency_ms: rl.latency_ms,
      ttft_ms: rl.ttft_ms,
      provider_cost_usd: rl.provider_cost_usd
    })
  end

  @doc """
  Lists request logs with `inserted_at` strictly after `since` (DateTime),
  ordered newest-first. Used by the MonitoringLive real-time subscription to
  fetch new logs appended after page load.

  Same filter support as `list_logs/1` (scope, status, agent, etc.), but
  the `before` cursor is ignored. A defensive `limit` caps how many new
  logs are returned in a single real-time refresh (default 500 — or 100
  when no `since` cursor is supplied).
  """
  def list_logs_after(since, filters \\ %{})

  def list_logs_after(nil, filters) do
    list_logs(Map.put(filters, :limit, Map.get(filters, :limit, 100)))
  end

  def list_logs_after(%DateTime{} = since, filters) do
    filters =
      filters
      |> Map.delete(:before)
      |> Map.delete("before")
      |> Map.put(:after, since)

    limit = clamp_limit(Map.get(filters, :limit) || Map.get(filters, "limit") || 500)

    RequestLog
    |> apply_log_filters(filters)
    |> order_by([rl], desc: rl.inserted_at)
    |> limit(^limit)
    |> preload(group_member: [:user, :group])
    |> preload(service: [:api_key])
    |> preload(:provider)
    |> Repo.all()
  end

  @doc """
  Lists request logs for a specific group, joining through `group_members`.

  Filters are the same as `list_logs/1`.
  """
  def list_logs_for_group(group_id, filters \\ %{}) do
    limit = clamp_limit(Map.get(filters, :limit) || Map.get(filters, "limit"))

    RequestLog
    |> join(:inner, [rl], tm in GroupMember, on: rl.group_member_id == tm.id)
    |> where([rl, tm], tm.group_id == ^group_id)
    |> apply_log_filters(filters)
    |> order_by([rl], desc: rl.inserted_at)
    |> limit(^limit)
    |> Repo.all()
  end

  defp apply_log_filters(query, filters) do
    query
    |> maybe_where(:group_member_id, filters)
    |> maybe_where(:service_id, filters)
    |> maybe_where_subject_id(filters)
    |> maybe_where(:subject_type, filters)
    |> maybe_where(:api_key_id, filters)
    |> maybe_where_member_ids(filters)
    |> maybe_where_user_ids(filters)
    |> maybe_where_group_id(filters)
    |> maybe_where(:provider_id, filters)
    |> maybe_where(:credential_id, filters)
    |> maybe_where(:model_provider_id, filters)
    |> maybe_where(:model_id, filters)
    |> maybe_where(:agent_type, filters)
    |> maybe_where(:status_code, filters)
    |> maybe_status_class(filters)
    |> maybe_model_search(filters)
    |> maybe_error_reason(filters)
    |> maybe_where(:streaming, filters)
    |> maybe_from(filters)
    |> maybe_to(filters)
    |> maybe_before(filters)
    |> maybe_after(filters)
  end

  # Filter by group_id through the group_members join. When group_id is present we
  # INNER JOIN group_members so the WHERE references both bindings.
  defp maybe_where_group_id(query, filters) do
    value = Map.get(filters, :group_id) || Map.get(filters, "group_id")

    case value do
      nil ->
        query

      group_id ->
        tm =
          GroupMember
          |> where([tm], tm.group_id == ^group_id)
          |> select([tm], tm.id)

        where(query, [rl], rl.group_member_id in subquery(tm))
    end
  end

  defp maybe_where(query, field, filters) do
    value = Map.get(filters, field)
    value = if is_nil(value), do: Map.get(filters, to_string(field)), else: value

    if is_nil(value), do: query, else: where(query, [rl], field(rl, ^field) == ^value)
  end

  defp maybe_where_member_ids(query, filters) do
    value = Map.get(filters, :group_member_ids) || Map.get(filters, "group_member_ids")

    case value do
      nil -> query
      ids when is_list(ids) -> where(query, [rl], rl.group_member_id in ^ids)
    end
  end

  # Scoping por usuario (identidad durable): el camino del dashboard y de
  # cualquier lectura que deba cuadrar con el motor de créditos.
  defp maybe_where_user_ids(query, filters) do
    value = Map.get(filters, :user_ids) || Map.get(filters, "user_ids")

    case value do
      nil -> query
      ids when is_list(ids) -> where(query, [rl], rl.user_id in ^ids)
    end
  end

  # Matches a log whose subject is *either* a group member or a service with
  # the given id. Used by `Budgets.Manager` (which keys both member and service
  # spend by a single binary subject id) to lazily load spend from the durable
  # log table without knowing which kind of subject it is.
  defp maybe_where_subject_id(query, filters) do
    case Map.get(filters, :subject_id) || Map.get(filters, "subject_id") do
      nil -> query
      id -> where(query, [rl], rl.group_member_id == ^id or rl.service_id == ^id)
    end
  end

  defp maybe_status_class(query, filters) do
    case Map.get(filters, :status_class) || Map.get(filters, "status_class") do
      nil -> query
      "" -> query
      "2xx" -> where(query, [rl], rl.status_code >= 200 and rl.status_code < 300)
      "4xx" -> where(query, [rl], rl.status_code >= 400 and rl.status_code < 500)
      "5xx" -> where(query, [rl], rl.status_code >= 500 and rl.status_code < 600)
      "errors" -> where(query, [rl], rl.status_code >= 400)
      _ -> query
    end
  end

  defp maybe_model_search(query, filters) do
    case Map.get(filters, :model_search) || Map.get(filters, "model_search") do
      nil ->
        query

      "" ->
        query

      search ->
        # Double ILIKE on free text. A catalog-resolved `model_id in ^ids OR
        # ilike(...)` variant was tried and reverted: the OR kills the index
        # plan anyway (EXPLAIN: per-partition seq scan) and dropping the
        # model_responded arm silently hid rows where only the responded
        # model matches (regression, no test covered it). Revisit only with
        # GIN trigram indexes on both columns.
        pattern = "%#{search}%"

        where(
          query,
          [rl],
          ilike(rl.model_requested, ^pattern) or ilike(rl.model_responded, ^pattern)
        )
    end
  end

  defp maybe_error_reason(query, filters) do
    case Map.get(filters, :error_reason) || Map.get(filters, "error_reason") do
      nil -> query
      "" -> query
      reason -> where(query, [rl], rl.error_reason == ^reason)
    end
  end

  defp maybe_from(query, filters) do
    case normalize_bound(Map.get(filters, :from) || Map.get(filters, "from"), :start) do
      nil -> query
      from -> where(query, [rl], rl.inserted_at >= ^from)
    end
  end

  # --- Retention clamp (see `cost_summary/1`) -------------------------------
  #
  # Two shapes matter here and both were silent: `:from` absent entirely, and
  # `:from` older than the retention cutoff. In both cases the aggregate ran
  # over whatever partitions survive and reported the result as the total.
  defp clamp_to_retention(filters) do
    filters = Map.new(filters)
    cutoff = retention_cutoff()

    case normalize_bound(Map.get(filters, :from) || Map.get(filters, "from"), :start) do
      nil ->
        warn_truncated_summary(:missing_from)
        Map.put(filters, :from, cutoff)

      %DateTime{} = from ->
        if DateTime.compare(from, cutoff) == :lt do
          warn_truncated_summary({:before_cutoff, from})
          Map.put(filters, :from, cutoff)
        else
          filters
        end
    end
  end

  # The cutoff the purge uses: `today - retention_days`, at the start of that
  # UTC day. Same definition as the DROP, so "what survives" and "what the
  # clamp allows" can never disagree.
  defp retention_cutoff do
    Tokengate.Logs.PartitionWorker.cutoff_day() |> day_edge(:start)
  end

  @doc """
  Validates that a stats read declares its window.

  An aggregate over `request_logs` with no `:from` is not "everything": it is
  "whatever survived the retention", presented with a straight face. The
  facades that accept an optional window (`user_stats/2`, `service_stats/2`,
  `StatsQueries.summary/1`) call this before touching the table.

  In `:dev`/`:test` (`config :tokengate, :strict_stats_windows`) a missing
  `:from` RAISES, so a new caller fails loudly while it is being written. In
  production it warns and clamps to the retention cutoff instead of crashing a
  dashboard: a labelled partial number beats a 500.

  Returns the filters with a guaranteed `:from`.
  """
  @spec ensure_window!(map() | keyword(), String.t()) :: map()
  def ensure_window!(filters, fun) do
    filters = Map.new(filters)

    case normalize_bound(Map.get(filters, :from) || Map.get(filters, "from"), :start) do
      nil ->
        if strict_stats_windows?() do
          raise ArgumentError, """
          #{fun} was called without :from.

          This read aggregates `request_logs`, which is pruned to \
          #{Tokengate.Logs.PartitionWorker.retention_days()} days, so an \
          unbounded window silently returns "last #{Tokengate.Logs.PartitionWorker.retention_days()} days" \
          as if it were the total. Pass an explicit `:from` (a DateTime, Date \
          or ISO-8601 string) inside the retention window.
          """
        else
          warn_truncated_summary(:missing_from)
          Map.put(filters, :from, retention_cutoff())
        end

      %DateTime{} = from ->
        if DateTime.compare(from, retention_cutoff()) == :lt do
          warn_truncated_summary({:before_cutoff, from})
          Map.put(filters, :from, retention_cutoff())
        else
          filters
        end
    end
  end

  defp strict_stats_windows? do
    Application.get_env(:tokengate, :strict_stats_windows, false)
  end

  defp warn_truncated_summary(reason) do
    days = Tokengate.Logs.PartitionWorker.retention_days()

    Logger.warning(
      "Logs.cost_summary/1 returned a TRUNCATED total (#{describe_truncation(reason)}). " <>
        "request_logs keeps only the last #{days} days " <>
        "(cutoff #{Date.to_iso8601(Tokengate.Logs.PartitionWorker.cutoff_day())}). " <>
        "Pass an explicit :from inside the window. Caller: #{summary_caller()}"
    )
  end

  defp describe_truncation(:missing_from), do: "no :from given"

  defp describe_truncation({:before_cutoff, from}),
    do: "from #{DateTime.to_iso8601(from)} is older than the cutoff"

  defp describe_truncation(_), do: "window older than the cutoff"

  # Best-effort attribution: this warning only fires on the pathological path,
  # so the cost of walking a stacktrace is paid once, not per request.
  defp summary_caller do
    case Process.info(self(), :current_stacktrace) do
      {:current_stacktrace, frames} ->
        Enum.find_value(frames, "unknown", fn
          {mod, fun, arity, _loc} when mod not in [Tokengate.Logs, Logger, Process] ->
            "#{inspect(mod)}.#{fun}/#{arity}"

          _ ->
            nil
        end)

      _ ->
        "unknown"
    end
  end

  defp maybe_to(query, filters) do
    case normalize_bound(Map.get(filters, :to) || Map.get(filters, "to"), :end) do
      nil -> query
      to -> where(query, [rl], rl.inserted_at <= ^to)
    end
  end

  # Date bounds come from HTTP params: a live filter, a CSV query string, or a
  # caller that hands over a plain string. Handing the raw value to Ecto raised
  # `Ecto.Query.CastError` and killed whatever LiveView/socket was holding it
  # (`F17`/`P15`: "string → datetime o filtro ignorado, nunca socket muerto").
  # This normalizes what it can and DROPS what it cannot understand.
  defp normalize_bound(nil, _edge), do: nil

  defp normalize_bound(%DateTime{} = dt, _edge), do: dt

  defp normalize_bound(%NaiveDateTime{} = ndt, _edge), do: DateTime.from_naive!(ndt, "Etc/UTC")

  defp normalize_bound(%Date{} = date, edge), do: day_edge(date, edge)

  defp normalize_bound(value, edge) when is_binary(value) do
    case String.trim(value) do
      "" ->
        nil

      trimmed ->
        case DateTime.from_iso8601(trimmed) do
          {:ok, dt, _offset} -> dt
          _ -> normalize_date_string(trimmed, edge)
        end
    end
  end

  defp normalize_bound(_value, _edge), do: nil

  defp normalize_date_string(value, edge) do
    case Date.from_iso8601(value) do
      {:ok, date} -> day_edge(date, edge)
      _ -> nil
    end
  end

  # A bare date spans its whole UTC day: the lower edge is 00:00:00 and the
  # upper edge is 23:59:59 (`inserted_at` is timestamp(0)).
  defp day_edge(date, :start), do: DateTime.new!(date, ~T[00:00:00], "Etc/UTC")
  defp day_edge(date, :end), do: DateTime.new!(date, ~T[23:59:59], "Etc/UTC")

  # Keyset cursor for the paginated feeds. `inserted_at` is `timestamp(0)`, so
  # a timestamp-only cursor either repeats or skips the rows that share the
  # boundary second. `before` therefore accepts the `{inserted_at, id}` tuple
  # the feeds carry — compared as a ROW, it walks the
  # `(inserted_at DESC, id DESC)` index monotonically — and still accepts a
  # bare DateTime for callers that only have the timestamp.
  defp maybe_before(query, filters) do
    case Map.get(filters, :before) || Map.get(filters, "before") do
      nil ->
        query

      {%DateTime{} = before_ts, before_id} when is_binary(before_id) ->
        where(
          query,
          [rl],
          fragment(
            "(?, ?) < (?, ?)",
            rl.inserted_at,
            rl.id,
            type(^before_ts, :utc_datetime),
            type(^before_id, :binary_id)
          )
        )

      %DateTime{} = before ->
        where(query, [rl], rl.inserted_at < ^before)

      other ->
        case normalize_bound(other, :end) do
          nil -> query
          before -> where(query, [rl], rl.inserted_at < ^before)
        end
    end
  end

  defp maybe_after(query, filters) do
    case normalize_bound(Map.get(filters, :after) || Map.get(filters, "after"), :start) do
      nil -> query
      after_dt -> where(query, [rl], rl.inserted_at > ^after_dt)
    end
  end

