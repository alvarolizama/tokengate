      seguiría viendo el gasto borrado y rechazando con 402 a usuarios con
      saldo limpio.

  Returns `{rows_truncated, nil}` as a sentinel (TRUNCATE does not return a
  row count).
  """
  @spec truncate_request_logs() :: {integer(), nil}
  def truncate_request_logs do
    Repo.transaction(fn ->
      Repo.query!("TRUNCATE TABLE request_logs RESTART IDENTITY CASCADE")

      # Truncate en la MISMA transacción: si algo falla, no queda el rollup
      # limpio con logs crudos (o al revés).
      Repo.query!("TRUNCATE TABLE request_metrics_hourly")

      # Los contadores durables son DERIVADOS de los logs que se acaban de
      # borrar: dejarlos vivos reportaría gasto de filas que ya no existen
      # (gasto fantasma en todos los totales) y un top-up que figura drenado
      # para siempre. Van en la misma transacción por la misma razón.
      Repo.query!("TRUNCATE TABLE consumption_counters")
      Repo.query!("TRUNCATE TABLE topup_consumption_counters")
    end)

    # Jobs pendientes de la cola :logs cancelados (ejecutarlos re-insertaría
    # los logs recién truncados): available/retryable/scheduled/executing.
    {:ok, _cancelled} =
      Oban.cancel_all_jobs(
        from(j in Oban.Job,
          where: j.queue == "logs" and j.state in ~w(available retryable scheduled executing)
        )
      )

    # Derived state in ETS.
    :ok = Tokengate.Metrics.Collector.reset()
    :ok = Tokengate.Metrics.DashboardCache.invalidate_all()
    _counters = Tokengate.Budgets.Manager.reset_monthly_counters()
    # Los bolsines de top-up miden su consumo contra request_logs: con la tabla
    # truncada hay que borrarlos también o quedan congelados con gasto fantasma
    # (402 contra top-ups con saldo limpio). El ciclo mensual NO hace esto.
    _topups = Tokengate.Budgets.Manager.clear_topup_counters()

    {0, nil}
  end

  @doc """
  Aggregated stats for a set of group_member_ids (used by the user-detail
  stats page). Pass a list to consolidate across multiple memberships.

  Combines:
    * cost & token totals over the given range (the whole lifetime unless
      `:from`/`:to` are passed), plus a `realtime_5min` rolling window,
    * request_count and per-status-class breakdown,
    * top 5 models used (by request count, descending),
    * last request timestamp (or `nil`).

  Filters out logs with `group_member_id == nil` (services etc.).

  ## Options

    * `:from` — `inserted_at >= from` (DateTime). Optional.
    * `:to`   — `inserted_at <= to` (DateTime). Optional.
  """
  @spec member_stats(binary() | [binary()], keyword() | map()) :: map()
  def member_stats(group_member_ids, opts \\ [])
      when is_list(group_member_ids) or is_binary(group_member_ids) do
    ids = if is_binary(group_member_ids), do: [group_member_ids], else: group_member_ids

    opts_map =
      cond do
        is_map(opts) -> opts
        is_list(opts) -> Map.new(opts)
        true -> %{}
      end

    summary =
      if ids == [] do
        %{
          total_cost_usd: Decimal.new(0),
          total_prompt_tokens: 0,
          total_completion_tokens: 0,
          total_cache_read_tokens: 0,
          total_cache_creation_tokens: 0,
          request_count: 0,
          avg_latency_ms: nil,
          avg_tps: nil,
          avg_ttft_ms: nil
        }
      else
        cost_summary_for_members(ids, opts_map)
      end

    range =
      opts_map
      |> Map.take([:from, :to])
      |> Enum.reject(fn {_k, v} -> is_nil(v) end)
      |> Map.new()

    status_class_breakdown =
      if ids == [],
        do: %{"2xx" => 0, "4xx" => 0, "5xx" => 0},
        else: status_breakdown_for_ids(ids, opts_map)

    top_models = if ids == [], do: [], else: top_models_for_ids(ids, 5, opts_map)

    last_request_at =
      if ids == [] do
        nil
      else
        RequestLog
        |> where([rl], rl.group_member_id in ^ids)
        |> apply_member_stats_range(range)
        |> select([rl], rl.inserted_at)
        |> order_by([rl], desc: rl.inserted_at)
        |> limit(1)
        |> Repo.one()
      end

    realtime_window =
      if ids == [] do
        %{request_count: 0, error_count: 0, avg_latency_ms: nil, error_rate: 0.0}
      else
        RequestLog
        |> where([rl], rl.group_member_id in ^ids)
        |> apply_member_stats_range(range)
        |> realtime_summary_for_member()
      end

    Map.merge(summary, %{
      status_breakdown: status_class_breakdown,
      top_models: top_models,
      last_request_at: last_request_at,
      realtime_5min: realtime_window
    })
  end

  defp apply_member_stats_range(query, %{from: from, to: to}) do
    query |> maybe_members_from(from) |> maybe_members_to(to)
  end

  # A half-open range is a NORMAL caller shape (`user_stats(id, from: ...)`,
  # `member_stats(ids, from: ...)` from the 5d/30d cards): pattern-matching only
  # the both-keys map silently DROPPED the bound, so the per-status and
  # top-models sub-queries scanned all 90 retained partitions (~90 index
  # probes + planning) while the summary was windowed. Bind each side on its
  # own so a partial range really bounds the query.
  defp apply_member_stats_range(query, %{from: from}), do: maybe_members_from(query, from)

  defp apply_member_stats_range(query, %{to: to}), do: maybe_members_to(query, to)

  defp apply_member_stats_range(query, _), do: query

