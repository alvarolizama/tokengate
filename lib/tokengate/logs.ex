  @doc """
  Per-user total historical spend across all group memberships.

  Returns `%{user_id => Decimal.t()}` — the sum of `provider_cost_usd`
  (the real cost) from all `request_logs`, grouped by user.
  Used by the admin users page for the "Gasto total" column.

  Groups by the denormalized `rl.user_id` column (carried on every row,
  indexed by `request_logs_user_inserted_idx`) — no join to `group_members`.
  The old inner join re-scanned every partition with a hash join AND
  dropped users whose membership was rotated away (the cascade deletes old
  `group_members` rows); grouping by the column keeps their lifetime spend
  visible, same subject-column semantics as `Credits.spend_grouped_users/2`.

  Hybrid read: hours older than the rollup's fresh tail answer from
  `request_metrics_hourly` (integer `cost_micro` sums) and only the last
  #{@rollup_tail_hours}h come from raw `request_logs`. Disabled in the test env by
  `config :tokengate, :stats_rollup, hybrid: false` (same flag as
  `Metrics.StatsQueries`), which keeps fixtures with arbitrary dates raw.
  """
  @spec total_spend_by_user() :: %{term() => Decimal.t()}
  def total_spend_by_user do
    # Durable counters first: one row per user per UTC day, so the lifetime
    # total is an index range instead of a GROUP BY over every retained
    # partition — and it keeps meaning "lifetime" after the retention drops old
    # days (a raw sum silently degrades to "last 90 days").
    if ConsumptionCounters.populated?() do
      ConsumptionCounters.spend_by_subject(:user)
    else
      raw_total_spend_by_user()
    end
  end

  # Raw/hybrid fallback, used only until the counters are backfilled.
  defp raw_total_spend_by_user do
    if rollup_hybrid?() do
      cutoff = rollup_cutoff()
      rollup = rollup_spend_by_user(cutoff)

      # Empty rollup for hours that DO have traffic means the backfill has not
      # run yet (fresh deploy) or the RollupWorker has been down (its tail
      # window is only @rollup_tail_hours — the gap would be permanent).
      # Fall back to the full raw aggregate, same guard as Rollup's
      # rollup-first reads.
      if map_size(rollup) == 0 and closed_hours_have_logs?(cutoff) do
        raw_spend_by_user(nil)
      else
        merge_spend_maps(rollup, raw_spend_by_user(cutoff))
      end
    else
      raw_spend_by_user(nil)
    end
  end

  defp closed_hours_have_logs?(cutoff) do
    Repo.exists?(
      from rl in RequestLog,
        where: not is_nil(rl.user_id) and rl.inserted_at < ^cutoff
    )
  end

  defp raw_spend_by_user(nil) do
    RequestLog
    |> where([rl], not is_nil(rl.user_id))
    |> group_by([rl], rl.user_id)
    |> select([rl], {rl.user_id, fragment("COALESCE(SUM(?::numeric), 0)", rl.provider_cost_usd)})
    |> Repo.all(timeout: stats_timeout())
    |> Map.new(fn {user_id, cost} -> {user_id, Decimal.new(to_string(cost))} end)
  end

  defp raw_spend_by_user(%DateTime{} = from) do
    RequestLog
    |> where([rl], not is_nil(rl.user_id) and rl.inserted_at >= ^from)
    |> group_by([rl], rl.user_id)
    |> select([rl], {rl.user_id, fragment("COALESCE(SUM(?::numeric), 0)", rl.provider_cost_usd)})
    |> Repo.all(timeout: stats_timeout())
    |> Map.new(fn {user_id, cost} -> {user_id, Decimal.new(to_string(cost))} end)
  end

  # Rollup half: buckets strictly before the cutoff are complete (the worker
  # re-aggregates the tail every minute), so `hour_utc < cutoff` never reads a
  # partially-written bucket.
  defp rollup_spend_by_user(%DateTime{} = cutoff) do
    # `day` is the leading column of every rollup index: without the upper
    # bound the planner cannot use it and the lifetime read seq-scans the
    # rollup table.
    RequestMetricsHourly
    |> where([m], not is_nil(m.user_id) and m.hour_utc < ^cutoff)
    |> where([m], m.day <= ^DateTime.to_date(cutoff))
    |> group_by([m], m.user_id)
    |> select([m], {m.user_id, fragment("COALESCE(SUM(?), 0)::bigint", m.cost_micro)})
    |> Repo.all(timeout: stats_timeout())
    |> Map.new(fn {user_id, micro} -> {user_id, micro_to_usd(micro)} end)
  end

  defp merge_spend_maps(rollup, raw) do
    Map.merge(rollup, raw, fn _user_id, a, b -> Decimal.add(a, b) end)
  end

  defp micro_to_usd(micro) when is_integer(micro) do
    micro |> Decimal.new() |> Decimal.div(Decimal.new(1_000_000))
  end

  # Same convention as `Metrics.StatsQueries`: the test env disables the split
  # (`stats_rollup: [hybrid: false]`) so fixtures with arbitrary dates answer
  # from raw request_logs without depending on the rollup worker.
  defp rollup_hybrid? do
    Application.get_env(:tokengate, :stats_rollup, [])[:hybrid] != false
  end

  # Freshness cut aligned to the hour: buckets >= this instant are re-read from
  # request_logs. Aligning avoids the half-covered bucket at the boundary.
  defp rollup_cutoff do
    DateTime.add(DateTime.utc_now(), -@rollup_tail_hours * 3600, :second)
    |> Map.merge(%{minute: 0, second: 0, microsecond: {0, 0}})
  end

  @doc """
  Per-service total spend. Returns `%{service_id => Decimal.t()}` — the sum of
  `provider_cost_usd` (the real cost) from `request_logs` grouped by service.
  Used by the admin services page for the "Gasto total" column.

  ## Why there is no rollup half here

  `total_spend_by_user/0` is hybrid because `request_metrics_hourly` carries
  `user_id`. It does NOT carry `service_id` (its dimensions are
  user/member/model/provider), so a per-service aggregate CANNOT be served
  from the rollup — any "hybrid" on this axis would silently under-count. The
  raw grouped scan stays, bounded by two things:

    * `:from` / `:to` — an explicit window. A caller that only renders a
      recent window pays only for that window's partitions; without them the
      read spans the retained history, which is what the column means.
    * the caller's shared cache. `services_live` reads this through
      `DashboardCache` (5s TTL), so N operators cost ONE scan per TTL. The
      per-service dimension belongs to the rollup only if `service_id` gets a
      column there (routed to the rollup phase, not invented here).
  """
  @spec total_spend_by_service(keyword() | map()) :: %{term() => Decimal.t()}
  def total_spend_by_service(opts \\ []) do
    {from, to} = spend_window(opts)

    # Lifetime (the "Total spend" column) comes from the durable counters: the
    # service axis has no rollup dimension, so this used to be a grouped scan of
    # every retained partition. An explicit window stays raw — the counters are
    # day-granular and a mid-day bound would over-include.
    if is_nil(from) and is_nil(to) and ConsumptionCounters.populated?() do
      ConsumptionCounters.spend_by_subject(:service)
    else
      RequestLog
      |> where([rl], not is_nil(rl.service_id))
      |> maybe_spend_from(from)
      |> maybe_spend_to(to)
      |> group_by([rl], rl.service_id)
      |> select(
        [rl],
        {rl.service_id, fragment("COALESCE(SUM(?::numeric), 0)", rl.provider_cost_usd)}
      )
      # Full-partition-spanning aggregate over a growing table: needs the
      # analytics budget, not the default 15s.
      |> Repo.all(timeout: stats_timeout())
      |> Map.new(fn {service_id, cost} -> {service_id, Decimal.new(to_string(cost))} end)
    end
  end

  defp spend_window(opts) when is_list(opts), do: spend_window(Map.new(opts))

  defp spend_window(opts) when is_map(opts) do
    from = normalize_bound(Map.get(opts, :from) || Map.get(opts, "from"), :start)
    to = normalize_bound(Map.get(opts, :to) || Map.get(opts, "to"), :end)
    {from, to}
  end

  defp maybe_spend_from(query, nil), do: query
  defp maybe_spend_from(query, from), do: where(query, [rl], rl.inserted_at >= ^from)

  defp maybe_spend_to(query, nil), do: query
  defp maybe_spend_to(query, to), do: where(query, [rl], rl.inserted_at <= ^to)

  @doc """
  Truncates all request logs. This is a **destructive operation** that
  removes every row from `request_logs` while preserving the table
  structure and partitions.

  Un reset de verdad tiene que limpiar TODO lo que deriva de los logs, no
  sólo la tabla cruda — si no, el Resumen híbrido de /stats sigue sirviendo
  las sumas viejas del rollup mientras En vivo (crudo) da 0, y los KPIs
  quedan descuadrados justo después de "reiniciar":

